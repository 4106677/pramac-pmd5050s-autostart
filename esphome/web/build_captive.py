#!/usr/bin/env python3
"""Builds components/captive_portal/captive_index.h from web/wifi.html with web/app.css inlined.

Run after changing wifi.html or app.css:  python3 esphome/web/build_captive.py
(app.js and app.css of the control page are embedded by ESPHome itself at compile time.)
"""
import gzip
import pathlib
import re

WEB = pathlib.Path(__file__).resolve().parent
OUT = WEB.parent / "components" / "captive_portal" / "captive_index.h"


def mini_css(css: str) -> str:
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    css = re.sub(r"\s*\n\s*", "", css)
    return re.sub(r"\s*([{};,])\s*", r"\1", css)


html = (WEB / "wifi.html").read_text(encoding="utf-8")
assert "/*APP_CSS*/" in html
html = html.replace("/*APP_CSS*/", mini_css((WEB / "app.css").read_text(encoding="utf-8")))
html = re.sub(r"\n\s*//[^\n]*", "\n", html)          # drop whole-line JS comments
html = re.sub(r"\n\s+", "\n", html)                  # drop indentation
data = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)

rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
OUT.write_text(
    "#pragma once\n// Generated by web/build_captive.py from web/wifi.html + web/app.css. Do not edit.\n\n"
    '#include "esphome/core/hal.h"\n\nnamespace esphome {\nnamespace captive_portal {\n\n'
    "const uint8_t INDEX_GZ[] PROGMEM = {\n    " + ",\n    ".join(rows) + "};\n\n"
    "}  // namespace captive_portal\n}  // namespace esphome\n",
    encoding="utf-8",
)
print(f"{OUT.relative_to(WEB.parent)}: {len(html)} bytes html, {len(data)} bytes gzip")
